def main(paths):
    index = json.loads((ROOT/'seed/development/visual_assets/image_source_index.json').read_text('utf-8'))
    verified = {}
    for filename in paths:
        path = Path(filename)
        raw = path.read_bytes()
        assert hashlib.sha256(raw).hexdigest() == index['source_zip_sha256'][path.name], path.name
        with zipfile.ZipFile(io.BytesIO(raw)) as archive:
            for member in archive.infolist():
                if member.is_dir():
                    continue
                assert Path(member.filename).name == member.filename, member.filename
                expected = index['assets'][member.filename]['sha256']
                content = archive.read(member)
                assert hashlib.sha256(content).hexdigest() == expected, member.filename
                assert member.filename not in verified, member.filename
                verified[member.filename] = (content, path.name)
    assert set(verified) == {stem+'.png' for stem, _, _ in MODELS}
    out = ROOT/'browser/assets/equipment'
    (out/'original').mkdir(parents=True, exist_ok=True)
    (out/'preview').mkdir(exist_ok=True)
    records = []
    for stem, name, aliases in MODELS:
        original = stem+'.png'
        content, archive = verified[original]
        (out/'original'/original).write_bytes(content)
        image = Image.open(io.BytesIO(content))
        width, height = image.size
        image.thumbnail((840, 840), Image.Resampling.LANCZOS)
        image.convert('RGB').save(out/'preview'/(stem+'.webp'), 'WEBP', quality=86, method=6)
        records.append(dict(name=name, aliases=aliases, original='assets/equipment/original/'+original,
                            preview='assets/equipment/preview/'+stem+'.webp', width=width, height=height,
                            sha256=hashlib.sha256(content).hexdigest(), source_archive=archive))
    manifest = '// Verified original posters; generated by scripts/import_equipment_images.py.\nexport const equipmentImages = '+json.dumps(records, ensure_ascii=False, indent=2)+';\n'
    (ROOT/'browser/equipment-image-data.js').write_bytes(manifest.encode('utf-8'))
    print(json.dumps({'images': len(records), 'original_bytes': sum(len(v[0]) for v in verified.values()),
                      'preview_bytes': sum(p.stat().st_size for p in (out/'preview').glob('*'))}))


if __name__ == '__main__':
    main(sys.argv[1:])
