import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {modelCall} from '../browser/model.js';
const contract=JSON.parse(readFileSync('docs/model-contract.json')).generation;
const config={api_key:'SYNTHETIC_TEST_KEY',base_url:'https://api.deepseek.com',model_id:'deepseek-flash',protocol:'chat_completions'};
let captured;
globalThis.fetch=async(url,options)=>{captured={url,options};return new Response(JSON.stringify({choices:[{finish_reason:'stop',message:{content:JSON.stringify({kind:'answer',message:'SYNTHETIC',payload_json:'{}',choices:[]})}}]}));};
const packet={mode:'query',original_intent:'synthetic test',context:{public:true,source_library:{source_ref:'state.json#/synthetic',date:'8363-12-11'}}};
await modelCall(config,contract,packet);
const body=JSON.parse(captured.options.body);
assert.equal(captured.url,'https://api.deepseek.com/chat/completions');
assert.equal(captured.options.credentials,'omit');assert.equal(captured.options.redirect,'error');
assert.equal(body.max_tokens,10000);assert.deepEqual(body.response_format,{type:'json_object'});
assert(!captured.options.body.includes(config.api_key));assert.equal(JSON.stringify(packet).includes(config.api_key),false);
assert(contract.instructions.includes('指挥官问询使用舰队汇报口吻'));
assert(contract.instructions.includes('普通探索、交谈、开场和剧情推进采用小说式叙述'));
assert(contract.instructions.includes('不写全知旁白'));
assert(contract.instructions.includes('不要求玩家填写内部ID'));
assert(!contract.instructions.includes('回答既有设定时注明来源文件与资料日期'));
assert(contract.instructions.includes('内部 payload_json 的结构、标识及证据引用仍严格按契约填写'));
assert(captured.options.body.includes('state.json#/synthetic'),'Internal evidence still reaches the model');
globalThis.fetch=async()=>new Response(JSON.stringify({choices:[{finish_reason:'length',message:{content:'{}'}}]}));
await assert.rejects(()=>modelCall(config,contract,packet),/MODEL_INCOMPLETE_OR_REFUSED/);
globalThis.fetch=async()=>new Response(JSON.stringify({choices:[{finish_reason:'stop',message:{content:'{"kind":"answer"}'}}]}));
await assert.rejects(()=>modelCall(config,contract,packet),/MODEL_SCHEMA_INVALID/);
globalThis.fetch=async()=>new Response('Do not echo provider error bodies',{status:401});
await assert.rejects(()=>modelCall(config,contract,packet),/^Error: MODEL_HTTP_401$/);
console.log('PASS: direct browser API, credentials handling, incomplete output, schema failure, stable errors');
